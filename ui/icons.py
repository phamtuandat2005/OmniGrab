# Bộ nhớ đệm cache icon
_ICON_CACHE: Dict[str, QIcon] = {}


def get_svg_icon(name: str, color: Optional[str] = None, size: int = 16) -> QIcon:
    """
    Trả về QIcon từ định nghĩa SVG chuẩn.

    Args:
        name: Tên icon trong SVG_PATHS.
        color: Mã màu hex (mặc định '#cbd5e1' nếu stroke, '#3b82f6' nếu thương hiệu).
        size: Kích thước pixel (mặc định 16).
    """
    if color is None:
        if name in ("play", "pause", "stop"):
            color = "#f8fafc"
        elif name == "tiktok":
            color = "#cbd5e1"
        elif name == "youtube":
            color = "#ef4444"
        elif name == "check":
            color = "#10b981"
        else:
            color = "#cbd5e1"

    cache_key = f"{name}:{color}:{size}"
    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    template = SVG_PATHS.get(name)
    if not template:
        # Fallback rỗng nếu không tìm thấy tên
        return QIcon()

    svg_content = template.format(color=color)
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    icon = QIcon(pixmap)
    _ICON_CACHE[cache_key] = icon
    return icon


def get_svg_pixmap(name: str, color: Optional[str] = None, size: int = 24) -> QPixmap:
    """Trả về QPixmap trực tiếp từ vector SVG."""
    if color is None:
        color = "#cbd5e1"
    template = SVG_PATHS.get(name)
    if not template:
        pix = QPixmap(size, size)
        pix.fill(Qt.GlobalColor.transparent)
        return pix

    svg_content = template.format(color=color)
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return pixmap
